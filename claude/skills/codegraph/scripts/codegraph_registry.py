#!/usr/bin/env python3
"""
codegraph_registry.py — Shared Brain（複数プロジェクト横断レジストリ）

動画 Graphify の Agentic OS「Shared Brain」のコード版 Phase A。`--base`（既定 ~/Project）
配下の各プロジェクトに codegraph を実行し、プロジェクトごとの CODEMAP.md と、それらを
集約した REGISTRY.md（1つの脳のインデックス）を生成する。Git 管理下のリポジトリに
出力すれば、ラップトップ・ダッシュボードのどこからも同じコード地図を参照できる。

設計方針:
  - codegraph.py を再利用（追加依存ゼロ）。ソースは一切変更せず、出力先のみに書く。
  - トークン節約量を推定表示（全ソース読み vs 地図読み）。

Usage:
    python tools/codegraph_registry.py [--base PATH] [--out PATH]
"""

from __future__ import annotations

import argparse
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import codegraph  # noqa: E402

CHARS_PER_TOKEN = 4  # 粗い近似（英数中心で 1 token ≈ 4 文字）
DEFAULT_BASE = Path(os.environ.get("CODEGRAPH_BASE", Path.home() / "Project"))
DEFAULT_OUT = Path(os.environ.get("CODEGRAPH_REGISTRY", Path.home() / ".claude" / "registry"))


def _est_tokens(chars: int) -> int:
    return chars // CHARS_PER_TOKEN


# ──────────────────────────────────────────────
# discover_projects
# ──────────────────────────────────────────────

def discover_projects(base: Path) -> list[Path]:
    """Return immediate subdirectories of *base* that contain source files."""
    projects: list[Path] = []
    for child in sorted(base.iterdir()):
        if not child.is_dir():
            continue
        if child.name in codegraph.EXCLUDE_DIRS or child.name.startswith("."):
            continue
        if codegraph.scan_code(child):
            projects.append(child)
    return projects


# ──────────────────────────────────────────────
# project_summary
# ──────────────────────────────────────────────

def _collect(root: Path) -> tuple[list[Path], "codegraph.CodeGraph"]:
    files = codegraph.scan_code(root)
    return files, codegraph.build_graph(files, root)


def _summary(root: Path, files: list[Path], g: "codegraph.CodeGraph") -> dict[str, Any]:
    source_chars = 0
    for f in files:
        try:
            source_chars += len(f.read_text(encoding="utf-8", errors="replace"))
        except OSError:
            pass
    codemap_chars = len(codegraph.render_codemap(g, root))

    lang_counts: dict[str, int] = {}
    for n in g.nodes():
        lang = g.node_attr(n).get("lang", "?")
        lang_counts[lang] = lang_counts.get(lang, 0) + 1

    gods = codegraph.find_god_nodes(g, top_n=1)
    source_tokens = _est_tokens(source_chars)
    codemap_tokens = _est_tokens(codemap_chars)

    return {
        "name": root.name,
        "path": str(root),
        "modules": len(g.nodes()),
        "edges": sum(g.out_degree(n) for n in g.nodes()),
        "languages": lang_counts,
        "top_god": (gods[0] if gods else None),
        "source_tokens": source_tokens,
        "codemap_tokens": codemap_tokens,
        "saved_tokens": max(0, source_tokens - codemap_tokens),
    }


def project_summary(root: Path) -> dict[str, Any]:
    files, g = _collect(root)
    return _summary(root, files, g)


# ──────────────────────────────────────────────
# render_registry
# ──────────────────────────────────────────────

def _fmt_langs(langs: dict[str, int]) -> str:
    return ", ".join(f"{k}:{v}" for k, v in sorted(langs.items())) or "—"


def render_registry(summaries: list[dict[str, Any]]) -> str:
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    total_modules = sum(s["modules"] for s in summaries)
    total_edges = sum(s["edges"] for s in summaries)
    total_saved = sum(s["saved_tokens"] for s in summaries)

    lines = [
        "# Code Knowledge Graph — REGISTRY (Shared Brain)",
        "",
        f"**Generated**: {generated_at}  ",
        f"**Projects**: {len(summaries)}  ",
        f"**Total modules**: {total_modules}  ",
        f"**Total internal edges**: {total_edges}  ",
        f"**Estimated tokens saved / 1 full-read**: ~{total_saved:,}  ",
        "",
        "> 各プロジェクトの詳細は `<project>/CODEMAP.md` を参照。会話開始時はまず該当 CODEMAP を読む。",
        "",
        "| Project | Languages | Modules | Edges | Top God Node | Src tokens | Map tokens | Saved |",
        "|---------|-----------|---------|-------|--------------|-----------|-----------|-------|",
    ]
    for s in sorted(summaries, key=lambda x: (-x["modules"], x["name"])):
        god = f"`{s['top_god'][0]}` ({s['top_god'][1]})" if s["top_god"] else "—"
        lines.append(
            f"| [{s['name']}]({s['name']}/CODEMAP.md) | {_fmt_langs(s['languages'])} "
            f"| {s['modules']} | {s['edges']} | {god} "
            f"| {s['source_tokens']:,} | {s['codemap_tokens']:,} | {s['saved_tokens']:,} |"
        )

    lines += ["", "> Auto-generated by `tools/codegraph_registry.py`. Do NOT edit manually."]
    return "\n".join(lines)


# ──────────────────────────────────────────────
# build_registry
# ──────────────────────────────────────────────

def build_registry(projects: list[Path], out_dir: Path) -> list[dict[str, Any]]:
    """Generate per-project CODEMAP.md and the aggregated REGISTRY.md.

    Only writes inside *out_dir*; project sources are never modified.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    summaries: list[dict[str, Any]] = []
    for root in projects:
        files, g = _collect(root)
        codegraph.generate_output(g, out_dir / root.name, root)
        summaries.append(_summary(root, files, g))
    (out_dir / "REGISTRY.md").write_text(render_registry(summaries), encoding="utf-8")
    return summaries


# ──────────────────────────────────────────────
# CLI
# ──────────────────────────────────────────────

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a cross-project code graph registry")
    parser.add_argument("--base", type=Path, default=DEFAULT_BASE,
                        help=f"directory holding the projects (default: {DEFAULT_BASE})")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT,
                        help=f"output dir for the registry (default: {DEFAULT_OUT})")
    args = parser.parse_args(argv)

    base: Path = args.base.resolve()
    if not base.is_dir():
        print(f"[registry] ERROR: not a directory: {base}", file=sys.stderr)
        return 1

    projects = discover_projects(base)
    print(f"[registry] Found {len(projects)} projects under {base}", flush=True)
    summaries = build_registry(projects, args.out.resolve())

    total_saved = sum(s["saved_tokens"] for s in summaries)
    print(f"[registry] Wrote {args.out.resolve() / 'REGISTRY.md'} "
          f"(~{total_saved:,} tokens saved / full-read)", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
